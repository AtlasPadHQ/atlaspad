/**
 * Deterministic test vectors (fixed seeds, no secrets): `node scripts/gen-vectors.ts > test/vectors.json`.
 * test/vectors.test.ts asserts the committed file equals this output; the Rust test tests/client_vectors.rs re-encodes
 * every instruction independently and runs them against the real program in LiteSVM.
 */
import { Keypair, type PublicKey, type TransactionInstruction } from "@solana/web3.js";
import * as sv from "../src/index.ts";

export const PLACE_ID = "ChIJN1t_tDeuEmsRUsoyG83frY4";
export const SEEDS = {
  deployer: 1,
  attestor: 2,
  governance: 3,
  launcher: 4,
  mint: 5,
  owner: 6,
  newAttestor: 7,
  newGovernance: 8,
  guardian: 9,
  newGuardian: 10,
} as const;
export type Who = keyof typeof SEEDS;

export function kp(who: Who): Keypair {
  return Keypair.fromSeed(new Uint8Array(32).fill(SEEDS[who]));
}

const hex = (b: Uint8Array) => sv.toHex(b);
const ixJson = (name: string, ix: TransactionInstruction) => ({
  name,
  programId: ix.programId.toBase58(),
  keys: ix.keys.map((k) => ({ pubkey: k.pubkey.toBase58(), isSigner: k.isSigner, isWritable: k.isWritable })),
  dataHex: hex(ix.data),
});

export function vectors() {
  const k = Object.fromEntries((Object.keys(SEEDS) as Who[]).map((w) => [w, kp(w).publicKey])) as Record<Who, PublicKey>;
  const ph = sv.placeHash(PLACE_ID);
  const [config, configBump] = sv.configPda();
  const [vault, vaultBump] = sv.vaultPda(ph);
  const [vaultState, stateBump] = sv.vaultStatePda(ph);
  const ixs: [string, TransactionInstruction][] = [
    [
      "initializeConfig",
      sv.initializeConfig({ payer: k.deployer, attestor: k.attestor, governance: k.governance, guardian: k.guardian, claimWindowSecs: 259_200 }),
    ],
    ["registerLaunch", sv.registerLaunch({ launcher: k.launcher, attestor: k.attestor, placeHash: ph, mint: k.mint })],
    ["requestClaim1", sv.requestClaim({ attestor: k.attestor, newOwner: k.owner, placeHash: ph, nonce: 1 })],
    ["cancelClaimByClaimant", sv.cancelClaim({ authority: k.owner, placeHash: ph })],
    ["requestClaim2", sv.requestClaim({ attestor: k.attestor, newOwner: k.owner, placeHash: ph, nonce: 2n })],
    ["finalizeClaim", sv.finalizeClaim({ placeHash: ph })],
    ["withdraw", sv.withdraw({ owner: k.owner, placeHash: ph })],
    ["unwrapWsol", sv.unwrapWsol({ placeHash: ph, wsolAccount: sv.vaultWsolAta(vault) })],
    ["cancelClaimByGuardian", sv.cancelClaim({ authority: k.guardian, placeHash: ph })],
    ["setPausedTrue", sv.setPaused({ authority: k.governance, paused: true })],
    ["setPausedFalse", sv.setPaused({ authority: k.guardian, paused: false })],
    ["proposeAttestor", sv.proposeAttestor({ governance: k.governance, newAttestor: k.newAttestor })],
    ["acceptAttestor", sv.acceptAttestor({ caller: k.guardian })],
    ["cancelAttestorProposal", sv.cancelAttestorProposal({ authority: k.governance })],
    ["proposeGuardian", sv.proposeGuardian({ governance: k.governance, newGuardian: k.newGuardian })],
    ["acceptGuardian", sv.acceptGuardian({ caller: k.guardian })],
    ["cancelGuardianProposal", sv.cancelGuardianProposal({ authority: k.governance })],
    ["proposeGovernance", sv.proposeGovernance({ governance: k.governance, newGovernance: k.newGovernance })],
    ["withdrawGovernanceProposal", sv.withdrawGovernanceProposal({ authority: k.governance })],
    ["acceptGovernance", sv.acceptGovernance({ newGovernance: k.newGovernance })],
  ];
  const sig = new Uint8Array(64).fill(0xab);
  const launchMsg = sv.encodeLaunchAttestation({ cluster: "devnet", placeHash: ph, launcher: k.launcher, mint: k.mint, expiry: 1_791_421_200 });
  const claimMsg = sv.encodeClaimAttestation({ cluster: "mainnet", placeHash: ph, newOwner: k.owner, nonce: 7, expiry: -1 });
  return {
    note: "generated by client/scripts/gen-vectors.ts; keypairs are Keypair.fromSeed([seed; 32]) test keys, never funded on any cluster",
    programId: sv.SHOP_VAULT_PROGRAM_ID.toBase58(),
    placeId: PLACE_ID,
    placeHashHex: hex(ph),
    seeds: SEEDS,
    keys: Object.fromEntries(Object.entries(k).map(([n, p]) => [n, p.toBase58()])),
    pdas: {
      config: [config.toBase58(), configBump],
      vault: [vault.toBase58(), vaultBump],
      vaultState: [vaultState.toBase58(), stateBump],
      programData: sv.programDataPda().toBase58(),
      bondingCurve: sv.bondingCurvePda(k.mint).toBase58(),
      vaultWsolAta: sv.vaultWsolAta(vault).toBase58(),
    },
    instructions: ixs.map(([n, ix]) => ixJson(n, ix)),
    appendixA: {
      launchMessageHex: hex(launchMsg),
      claimMessageHex: hex(claimMsg),
      ed25519IxDataHex: hex(sv.ed25519AttestationInstruction({ attestor: k.attestor, signature: sig, message: launchMsg }).data),
    },
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.stdout.write(JSON.stringify(vectors(), null, 2) + "\n");
}
