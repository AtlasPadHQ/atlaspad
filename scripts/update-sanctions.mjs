#!/usr/bin/env node
/**
 * Rebuilds worker/data/sanctioned-wallets.json, the list the Worker screens wallets against (worker/sanctions.ts), from
 * the OFAC SDN list: Treasury's sdn_advanced.xml, every "Digital Currency Address - SOL" feature, plus USDC / USDT
 * entries that are Solana addresses (those tokens also live on Solana). Public data, no key, nothing sent anywhere;
 * the only file it writes is the JSON list.
 *
 *   node scripts/update-sanctions.mjs                 # download (~130 MB, a few minutes) and write the list
 *   node scripts/update-sanctions.mjs --file <xml>    # use a copy you downloaded yourself (curl -L -o sdn.xml <URL>)
 *   node scripts/update-sanctions.mjs --check         # exit 1 when the committed list is out of date (writes nothing)
 *
 * Then commit the JSON and redeploy: the list is bundled into the Worker. OFAC updates the SDN list several times a
 * month; run this at least monthly and whenever OFAC announces crypto designations (RUNBOOK "Sanctions screening").
 * It refuses to write a download that looks wrong (no SOL feature type, or fewer than half of the current addresses)
 * unless --force.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { isAddress } from './lib/b58.mjs';
import { bad, fatal, head, info, ok, parseArgs, sleep, warn } from './lib/log.mjs';
import { ROOT } from './lib/paths.mjs';

export const SDN_ADVANCED_URL = 'https://sanctionslistservice.ofac.treas.gov/api/PublicationPreview/exports/SDN_ADVANCED.XML';
export const LIST_PATH = join(ROOT, 'worker', 'data', 'sanctioned-wallets.json');
/** Asset feature types whose Solana-format addresses we keep (SOL itself, and SPL stablecoins). */
const ASSETS = ['SOL', 'USDC', 'USDT'];

/**
 * Solana addresses in an sdn_advanced.xml document. `rejected` lists SOL-feature values that are not valid addresses
 * (typos in the source are reported, never guessed at). Pure; unit-tested in scripts/test/sanctions.test.mjs.
 */
export function solAddressesFromSdn(xml) {
  const types = new Map();
  for (const m of xml.matchAll(/<FeatureType\b[^>]*\bID="(\d+)"[^>]*>\s*Digital Currency Address - ([A-Z0-9]+)\s*<\/FeatureType>/g)) {
    if (ASSETS.includes(m[2])) types.set(m[1], m[2]);
  }
  const addresses = new Set();
  const rejected = [];
  if (types.size) {
    const ids = [...types.keys()].join('|');
    const featureRe = new RegExp(`<Feature\\b[^>]*\\bFeatureTypeID="(${ids})"[^>]*>([\\s\\S]*?)<\\/Feature>`, 'g');
    for (const m of xml.matchAll(featureRe)) {
      const asset = types.get(m[1]);
      for (const v of m[2].matchAll(/<VersionDetail\b[^>]*>([^<]*)<\/VersionDetail>/g)) {
        const value = v[1].trim();
        if (isAddress(value)) addresses.add(value);
        else if (asset === 'SOL') rejected.push(value);
        // USDC / USDT values in another chain's format (0x…, T…) are not Solana wallets: skipped
      }
    }
  }
  const d = /<DateOfIssue\b[^>]*>\s*<Year>(\d{4})<\/Year>\s*<Month>(\d{1,2})<\/Month>\s*<Day>(\d{1,2})<\/Day>/.exec(xml);
  const listDate = d ? `${d[1]}-${d[2].padStart(2, '0')}-${d[3].padStart(2, '0')}` : null;
  return { addresses: [...addresses].sort(), rejected, listDate, solType: [...types.values()].includes('SOL') };
}

/** The JSON file's content (stable key order; `generatedAt` is the only field that changes on an unchanged list). */
export function listFile({ addresses, listDate }, generatedAt = new Date().toISOString().slice(0, 10)) {
  return {
    source: 'OFAC SDN list (sdn_advanced.xml): "Digital Currency Address - SOL", plus USDC / USDT entries in Solana format',
    url: SDN_ADVANCED_URL,
    listDate,
    generatedAt,
    note: 'Generated by scripts/update-sanctions.mjs. Do not edit by hand: rerun the script, commit, redeploy the Worker.',
    addresses,
  };
}

/** Why a fresh list must not replace the current one (empty = fine). */
export function updateProblems(next, current) {
  const out = [];
  if (!next.solType) out.push('the document has no "Digital Currency Address - SOL" feature type (not an SDN advanced file?)');
  if (!next.listDate) out.push('the document has no DateOfIssue');
  const cur = current?.addresses ?? [];
  if (cur.length >= 2 && next.addresses.length < Math.ceil(cur.length / 2)) {
    out.push(`only ${next.addresses.length} addresses, the current list has ${cur.length} (a truncated download?)`);
  }
  return out;
}

async function download(url) {
  let last = null;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      info(`downloading ${url} (attempt ${attempt}/3, ~130 MB)`);
      const res = await fetch(url, { headers: { accept: 'application/xml,text/xml' } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.text();
    } catch (e) {
      last = e;
      warn(`download failed: ${e.message}`);
      if (attempt < 3) await sleep(5_000 * attempt);
    }
  }
  throw new Error(`could not download the SDN list (${last?.message ?? 'error'}). Download it yourself and pass --file <path>.`);
}

function readCurrent() {
  try {
    return JSON.parse(readFileSync(LIST_PATH, 'utf8'));
  } catch {
    return null;
  }
}

async function main() {
  const args = parseArgs(process.argv.slice(2), ['check', 'force']);
  head('update-sanctions · OFAC SDN Solana addresses');
  const xml = typeof args.file === 'string' ? readFileSync(args.file, 'utf8') : await download(SDN_ADVANCED_URL);
  const next = solAddressesFromSdn(xml);
  const current = readCurrent();
  info(`SDN list of ${next.listDate ?? '?'}: ${next.addresses.length} Solana address(es)`);
  for (const r of next.rejected) warn(`not a valid Solana address in the SOL features, skipped: ${JSON.stringify(r)}`);
  const problems = updateProblems(next, current);
  for (const p of problems) bad(p);
  if (problems.length && !args.force) fatal('refusing to write the list (add --force if you are sure)');

  const same = !!current && JSON.stringify(current.addresses) === JSON.stringify(next.addresses) && current.listDate === next.listDate;
  if (args.check) {
    if (same) ok(`the committed list is current (${next.addresses.length} addresses, ${next.listDate})`);
    else bad(`the committed list is out of date (committed ${current?.listDate ?? 'none'}, OFAC ${next.listDate}); run without --check`);
    process.exit(same ? 0 : 1);
  }
  const added = next.addresses.filter((a) => !(current?.addresses ?? []).includes(a));
  const removed = (current?.addresses ?? []).filter((a) => !next.addresses.includes(a));
  writeFileSync(LIST_PATH, `${JSON.stringify(listFile(next), null, 2)}\n`);
  ok(`wrote ${LIST_PATH} (${next.addresses.length} addresses; +${added.length} −${removed.length})`);
  if (added.length || removed.length || !same) info('commit it and redeploy the Worker (the list is bundled at build time)');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => fatal(e.message));
}
